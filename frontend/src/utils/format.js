/**
 * Formats a number as ARS currency.
 * @param {number} value
 * @returns {string} Formatted currency string
 */
export const formatCurrency = (value) => {
    if (value === undefined || value === null) return '$ 0,00';
    const numStr = new Intl.NumberFormat('es-AR', {
        minimumFractionDigits: 2,
        maximumFractionDigits: 2
    }).format(value);
    return `$ ${numStr}`;
};

export const TIMEZONE_ARGENTINA = 'America/Argentina/Buenos_Aires';

// Matches ISO strings carrying an explicit UTC marker or offset AFTER the time part
// (e.g. "2026-10-20T05:55:00.000+00:00", "...Z", "...-03:00"). Date-only and naive values do not match.
const EXPLICIT_OFFSET_REGEX = /T.*(?:Z|[+-]\d{2}:?\d{2})$/i;

const hasExplicitOffset = (normalizedDateString) => EXPLICIT_OFFSET_REGEX.test(normalizedDateString);

const partsToMap = (parts) => Object.fromEntries(parts.map((part) => [part.type, part.value]));

/** YYYY-MM-DD of an instant as seen in the given IANA time zone (locale independent via formatToParts). */
const toYmd = (date, timeZone) => {
    const p = partsToMap(new Intl.DateTimeFormat('en-US', {
        timeZone,
        year: 'numeric',
        month: '2-digit',
        day: '2-digit'
    }).formatToParts(date));
    return `${p.year}-${p.month}-${p.day}`;
};

/**
 * Today's business date (YYYY-MM-DD) in Argentina, regardless of the device time zone.
 * Replaces new Date().toISOString().split('T')[0], which jumps to tomorrow between 21:00 and 23:59 (UTC-3).
 */
export const getTodayArgentina = () => toYmd(new Date(), TIMEZONE_ARGENTINA);

/**
 * Business date N calendar days before today in Argentina (YYYY-MM-DD).
 * Pure civil-calendar arithmetic on UTC: no dependency on the device time zone or DST.
 */
export const getDaysAgoArgentina = (days = 30) => {
    const [year, month, day] = getTodayArgentina().split('-').map(Number);
    return toYmd(new Date(Date.UTC(year, month - 1, day - days)), 'UTC');
};

/**
 * Argentine civil date (YYYY-MM-DD) of a date/datetime string, or null if none is found.
 * - Strings with explicit offset/Z are converted to Argentina time.
 * - Date-only / naive strings (backend sends naive Buenos Aires wall-clock) are used as-is.
 */
export const toDateKeyArgentina = (dateString) => {
    if (!dateString) return null;
    const normalized = String(dateString).replace(' ', 'T');
    if (hasExplicitOffset(normalized)) {
        const date = new Date(normalized);
        return Number.isNaN(date.getTime()) ? null : toYmd(date, TIMEZONE_ARGENTINA);
    }
    const match = normalized.match(/(\d{4}-\d{2}-\d{2})/);
    return match ? match[1] : null;
};

/** HH:mm of an instant in Argentina time (24h). */
export const formatTimeArgentina = (date) => new Intl.DateTimeFormat('es-AR', {
    timeZone: TIMEZONE_ARGENTINA,
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23'
}).format(date);

/**
 * Formats a date string (YYYY-MM-DD) to a readable format (DD/MM/YYYY).
 * @param {string} dateString
 * @returns {string} Formatted date
 */
export const formatDate = (dateString) => {
    if (!dateString) return '';

    let dateStr = dateString;
    // If it's just a date string "YYYY-MM-DD", append time to force local parsing and avoid UTC offset issues
    if (/^\d{4}-\d{2}-\d{2}$/.test(dateStr)) {
        dateStr += 'T00:00:00';
    }
    // If it has a space instead of T (like some SQL formats), replace it for Safari/JS compatibility
    dateStr = dateStr.replace(' ', 'T');

    const date = new Date(dateStr);

    if (isNaN(date.getTime())) {
        // Fallback for completely unrecognized formats
        return dateString;
    }

    // Instants with an explicit offset/Z (e.g. /api/cobros-y-pedidos serializes java.sql.Timestamp in UTC)
    // MUST be shown in Argentina time, never in the device's zone (the owner operates from Chile).
    if (hasExplicitOffset(dateStr)) {
        const p = partsToMap(new Intl.DateTimeFormat('en-US', {
            timeZone: TIMEZONE_ARGENTINA,
            year: 'numeric',
            month: '2-digit',
            day: '2-digit',
            hour: '2-digit',
            minute: '2-digit',
            second: '2-digit',
            hourCycle: 'h23'
        }).formatToParts(date));
        return `${p.hour}:${p.minute}:${p.second} - ${p.day}/${p.month}/${p.year}`;
    }

    // For naive strings generated by the backend (already in Argentina time, without timezone metadata),
    // extract components directly via regex to guarantee 100% determinism and immunity against foreign DST shifts.
    const match = dateStr.match(/^(\d{4})-(\d{2})-(\d{2})(?:[T\s](\d{2}):(\d{2})(?::(\d{2}))?)?/);
    if (match) {
        const [, year, month, day, h = '00', m = '00', s = '00'] = match;
        return `${h.padStart(2, '0')}:${m.padStart(2, '0')}:${s.padStart(2, '0')} - ${day}/${month}/${year}`;
    }

    // Fallback for non-standard formats
    const hours = String(date.getHours()).padStart(2, '0');
    const minutes = String(date.getMinutes()).padStart(2, '0');
    const seconds = String(date.getSeconds()).padStart(2, '0');
    const day = String(date.getDate()).padStart(2, '0');
    const month = String(date.getMonth() + 1).padStart(2, '0');
    const year = date.getFullYear();

    return `${hours}:${minutes}:${seconds} - ${day}/${month}/${year}`;
};

/**
 * Formats a date string (YYYY-MM-DD) to a readable format (DD/MM/YYYY) without time.
 * Strings with explicit offset/Z are converted to the Argentine civil date first.
 * @param {string} dateString
 * @returns {string} Formatted date without time
 */
export const formatDateOnly = (dateString) => {
    if (!dateString) return '';
    const key = toDateKeyArgentina(dateString);
    if (!key) return dateString;
    const [year, month, day] = key.split('-');
    return `${day}/${month}/${year}`;
};
